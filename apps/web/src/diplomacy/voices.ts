/**
 * What each race's leader says in an audience. Every built-in race has its own
 * voice; custom races speak with the plain envoy voice. `{you}` is the name of
 * the empire being addressed and `{us}` the speaker's own.
 */

export type Moment =
  /** Opening an audience, by how they feel about the visitor. */
  | "greet" | "greetWarm" | "greetCold" | "greetWar"
  /** The first meeting of two empires. */
  | "contact"
  /** Answers to the visitor's treaties, exchanges and peace offers. */
  | "accept" | "refuse"
  /** Answers to the visitor's demands. */
  | "yield" | "defy"
  /** They come to the visitor with a treaty, a swap, peace or a demand. */
  | "offer" | "peace" | "demand"
  /** How they take the visitor's answer to that. */
  | "thanks" | "spurned" | "obeyed" | "threat"
  /** War declared by them, or on them. */
  | "war" | "warReply"
  | "gift" | "broken" | "tired" | "farewell";

