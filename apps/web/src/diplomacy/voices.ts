/** The lines a race's leader has for a moment, falling back to the plain envoy voice. */
export function linesFor(raceId: string, moment: Moment): string[] {
  const own = VOICES[raceId]?.[moment];
  return own && own.length > 0 ? own : PLAIN[moment];
}

/** Picks one line, steadily for the same seed, and fills in the names. */
export function speak(raceId: string, moment: Moment, seed: number, names: { you: string; us: string }): string {
  const lines = linesFor(raceId, moment);
  const line = lines[Math.abs(Math.floor(seed)) % lines.length]!;
  return line.replaceAll("{you}", names.you).replaceAll("{us}", names.us);
}
